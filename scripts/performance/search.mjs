import assert from 'node:assert/strict';
import puppeteer from 'puppeteer';
const base = (process.argv[2] || 'http://localhost:4322').replace(/\/$/, '');
const browser = await puppeteer.launch({ headless: true, args: ['--no-sandbox','--disable-dev-shm-usage'] });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', error => errors.push(String(error)));
const indexRequests = [];
page.on('request', request => { if (new URL(request.url()).pathname.endsWith('/search-index.json')) indexRequests.push(request.url()); });
try {
  await page.goto(base + '/blog', { waitUntil: 'networkidle0' });
  assert.equal(indexRequests.length, 0);
  await page.goto(base + '/search', { waitUntil: 'networkidle0' });
  assert.equal(indexRequests.length, 0);
  console.log('PASS search index is not loaded on ordinary pages or before a query');
  await page.type('#search-query', 'future AI native');
  await page.waitForFunction(() => document.querySelector('#search-status').textContent.includes('result'));
  assert.match(await page.$eval('#search-results a', element => element.textContent), /AI-native/i);
  assert.ok((await page.$eval('#search-results a', element => element.href)).startsWith(base + '/blog/'));
  await page.focus('#search-query');
  await page.keyboard.press('ArrowDown');
  assert.equal(await page.evaluate(() => document.activeElement === document.querySelector('#search-results a')), true);
  await page.reload({ waitUntil: 'networkidle0' });
  assert.equal(await page.$eval('#search-query', element => element.value), 'future AI native');
  assert.ok(await page.$('#search-results a'));
  console.log('PASS ranked queries, keyboard focus, shareable URL and reload');
  await page.select('#search-section', 'projects');
  await page.waitForFunction(() => !document.querySelector('#search-results').hasAttribute('aria-busy'));
  assert.equal(await page.$$eval('#search-results a', links => links.every(link => link.pathname.includes('/projects/'))), true);
  await page.focus('#search-query');
  await page.keyboard.press('Escape');
  assert.equal(await page.$$eval('#search-results li', elements => elements.length), 0);
  assert.equal(await page.$eval('#search-browse', element => element.hidden), false);
  await page.type('#search-query', 'zz-no-results-8675309');
  await page.waitForFunction(() => document.querySelector('#search-status').textContent.startsWith('No results'));
  console.log('PASS category filtering, Escape, empty query and no-results message');
  await page.setJavaScriptEnabled(false);
  await page.goto(base + '/search', { waitUntil: 'networkidle0' });
  assert.equal(await page.$$eval('#search-browse a', links => links.length), 14);
  assert.ok((await page.$eval('noscript', element => element.textContent)).includes('archive'));
  await page.setJavaScriptEnabled(true);
  await page.setRequestInterception(true);
  let failIndex = true;
  page.on('request', request => request.url().endsWith('/search-index.json') && failIndex ? request.abort() : request.continue());
  await page.goto(base + '/search?q=design', { waitUntil: 'networkidle0' });
  assert.match(await page.$eval('#search-status', element => element.textContent), /could not load/);
  assert.equal(await page.$eval('#search-browse', element => element.hidden), false);
  failIndex = false;
  await page.click('button[type="submit"]');
  await page.waitForFunction(() => document.querySelector('#search-status').textContent.includes('result'));
  assert.ok(await page.$('#search-results a'));
  assert.deepEqual(errors, []);
  console.log('PASS no-JavaScript browsing, failed-load fallback, retry and no browser exceptions');
} finally { await browser.close(); }
